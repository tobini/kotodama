import type { ItemGroup, JlptLevel, Script } from './types';

// Vocabulario N5. Criterio (el mismo del examen): las palabras cuyos kanji no son
// de N5 se muestran en kana. Las que se escriben con kanji N5 van en el contenido de kanji.

/** [lectura, significado, lectura alternativa opcional] */
type Entry = [string, string, string?];

function wordGroup(script: Script, id: string, name: string, entries: Entry[], level: JlptLevel = 'N5'): ItemGroup {
  return {
    id: `words-${script}:${id}`,
    name,
    items: entries.map(([reading, meaning, alt]) => ({
      id: `word:${script}:${reading}`,
      text: reading,
      reading,
      altReadings: alt ? [alt] : undefined,
      meaning,
      script,
      kind: 'word',
      level,
      tags: [id],
    })),
  };
}

