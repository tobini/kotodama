// ---------------------------------------------------------------- palabras con kanji
// Solo palabras escritas con kanji N5; lo que lleva kanji de niveles superiores
// va en kana (como en el examen): 食べもの, 子ども, 友だち.

/** [texto, lectura, significado, otras lecturas válidas] */
type WordEntry = [text: string, reading: string, meaning: string, variants?: string[]];

function wordGroup(id: string, name: string, entries: WordEntry[]): ItemGroup {
  return {
    id: `words-kanji:${id}`,
    name,
    items: entries.map(([text, reading, meaning, variants]) => ({
      id: `word:kanji:${text}`,
      text,
      reading,
      variants,
      meaning,
      script: 'kanji',
      kind: 'word',
      level: 'N5',
      tags: [id],
    })),
  };
}

