import type { ItemGroup, StudyItem } from './types';

// ---------------------------------------------------------------- kanji sueltos
// Lecturas separadas por espacio: on'yomi en katakana, kun'yomi en hiragana.
// El punto separa el okurigana: "た.べる" se escribe "ta" y se muestra た(べる).

type KanjiEntry = [kanji: string, meaning: string, readings: string];

function kanjiGroup(id: string, name: string, entries: KanjiEntry[]): ItemGroup {
  return {
    id: `kanji:${id}`,
    name,
    items: entries.map(([kanji, meaning, readings]): StudyItem => {
      const list = readings.split(' ');
      const typed = list.map((r) => r.split('.')[0]);
      return {
        id: `kanji:${kanji}`,
        text: kanji,
        reading: typed[0],
        variants: typed.slice(1),
        spoken: list.map((r) => r.replace('.', '')),
        notes: list.map((r) => (r.includes('.') ? r.replace('.', '(') + ')' : r)).join('、'),
        meaning,
        script: 'kanji',
        kind: 'kanji',
        level: 'N5',
        tags: [id],
      };
    }),
  };
}

